"""Build the Sky Beta copies of the drift-correction FlyX files (and the safeguarded variant).

    python3 jolie_course/drift/build_drift_files.py

Inputs (read only):
  jolie_course/upload_to_flyx_drift.py   Jolie's jolie-drift-correction build (f7b97d3), native PX4
  jolie_course/skybeta_main.py.in        the Sky Beta main() used for upload_to_flyx_skybeta.py
  jolie_course/build_skybeta_copy.py     its PX4-I/O swap (reused, with SRC/OUT/MAIN redirected)
Outputs:
  jolie_course/upload_to_flyx_drift_skybeta.py
  jolie_course/upload_to_flyx_drift_safe.py           native PX4, safeguarded alignment
  jolie_course/upload_to_flyx_drift_safe_skybeta.py   Sky Beta, safeguarded alignment

The Sky Beta main gets the drift branch's alignment exactly as fly_pathplan has it: the same
``apply_alignment`` method (copied verbatim out of the native file's main), the same call after
``mission.plan()`` in ``on_plan`` and the same node state used by ``print_summary``.

The safe variant changes three things only (see jolie_course/drift/README.md for the evidence):
  * align_to_map: Tukey-robust weights (c = 0.08 m) and a stricter per-direction evidence
    threshold (min eigenvalue 30 instead of 10);
  * fly_pathplan: gain 0.3 (was 0.6), cap 0.6 m (was 1.5).
"""
from pathlib import Path
import importlib.util
import sys

HERE = Path(__file__).resolve().parent
JC = HERE.parent
DRIFT = JC / "upload_to_flyx_drift.py"


def _skybeta_builder():
    spec = importlib.util.spec_from_file_location("build_skybeta_copy", JC / "build_skybeta_copy.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _one(text, old, new, what):
    if text.count(old) != 1:
        raise SystemExit(f"{what}: expected exactly one match of:\n{old}")
    return text.replace(old, new)


def native_alignment_method(native):
    """The ``apply_alignment`` method of the native main, verbatim."""
    i = native.index("        def apply_alignment(self, shift):")
    k = native.index("        # ----------------------------------------------------------", i)
    return native[i:k]


def skybeta_main_with_alignment(native):
    main = (JC / "skybeta_main.py.in").read_text(encoding="utf-8")
    main = _one(main, '''            self.px4_modes, self.stalls = [], []
            self.intr = None''', '''            self.px4_modes, self.stalls = [], []
            self.align_total, self.align_steps, self.align_logged, self.align_capped = np.zeros(2), 0, -1e9, False
            self.intr = None''', "skybeta node state")
    main = _one(main, '''            ms = 1e3 * (time.perf_counter() - t0)
            if cmd is not None:''', '''            ms = 1e3 * (time.perf_counter() - t0)
            if planner.align is not None and mission.frame is not None:
                self.apply_alignment(planner.align)
            if cmd is not None:''', "skybeta on_plan")
    main = _one(main, '''        # ---------------------------------------------------------- control
''', native_alignment_method(native) + '''        # ---------------------------------------------------------- control
''', "skybeta apply_alignment")
    return main


class _Text:
    def __init__(self, text, name="input"):
        self.text, self.name = text, name

    def read_text(self, encoding=None):
        return self.text


def skybeta_copy(native_text, out, doc_note):
    b = _skybeta_builder()
    b.SRC, b.OUT, b.MAIN = _Text(native_text, out.name.replace('_skybeta', '')), out, _Text(skybeta_main_with_alignment(native_text))
    b.DOC = b.DOC.replace('"""Jolie\'s FlyX-proven planner (upload_to_flyx.py) on the Sky Beta contract - the drone\'s interface.',
                          '"""' + doc_note, 1)
    b.DOC = b.DOC.replace("GENERATED by jolie_course/build_skybeta_copy.py from upload_to_flyx.py, which completed the whole\ncourse in FlyX (native PX4).",
                          "GENERATED by jolie_course/drift/build_drift_files.py (build_skybeta_copy.py's swap) from\n" + out.name.replace("_skybeta", "") + ". The base it extends completed the whole course in FlyX (native PX4).")
    b.build()


def safe_native(native):
    s = native
    # 1) align_to_map inside the embedded depth_projection source: robust weights + stricter evidence
    s = _one(s, '''    shift = np.zeros(2)
    rms0 = None
    for _ in range(iterations):
        d = _bilinear(dist, spec, pts + shift)
        g = _bilinear(grad, spec, pts + shift)
        rms = float(np.sqrt(np.mean(d ** 2)))
        rms0 = rms if rms0 is None else rms0
        H = g.T @ g
        b = g.T @ d
        w, v = np.linalg.eigh(H)''', '''    shift = np.zeros(2)
    rms0 = None
    for _ in range(iterations):
        d = _bilinear(dist, spec, pts + shift)
        g = _bilinear(grad, spec, pts + shift)
        rms = float(np.sqrt(np.mean(d ** 2)))
        rms0 = rms if rms0 is None else rms0
        # SAFE: Tukey weights (c = ROBUST_C): hits far from the consensus (an unmapped obstacle by a
        # wall, one wall that moved) stop pulling the frame (drift-eval A/B, jolie_course/drift)
        wt = (1 - np.clip(np.abs(d) / ROBUST_C, 0, 1) ** 2) ** 2
        H = (g * wt[:, None]).T @ g
        b = (g * wt[:, None]).T @ d
        w, v = np.linalg.eigh(H)''', "safe align weights")
    s = _one(s, '''            if lam > max(10.0, .02 * len(pts)):''',
             '''            if lam > max(MIN_EVIDENCE, .02 * float(wt.sum())):''', "safe evidence threshold")
    s = _one(s, '''def align_to_map(points, dist, grad, spec, *, near=.35, min_points=40, iterations=5):''',
             '''ROBUST_C = .08          # SAFE: Tukey width, m
MIN_EVIDENCE = 30.0     # SAFE: per-direction wall evidence (Jolie: 10)


def align_to_map(points, dist, grad, spec, *, near=.35, min_points=40, iterations=5):''', "safe constants")
    # 2) fly_pathplan: smaller gain, lower cap
    s = _one(s, "ALIGN_MAX_M = 1.5\n", "ALIGN_MAX_M = .6                  # SAFE (drift-eval): was 1.5\nALIGN_GAIN = .3                   # SAFE (drift-eval): was 0.6\n", "safe cap")
    s = _one(s, "            step = .6 * np.asarray(shift, float)\n", "            step = ALIGN_GAIN * np.asarray(shift, float)\n", "safe gain")
    s = _one(s, "Generated by pathfinding/tools/build_single_file.py from flyx/fly_pathplan.py (commit f7b97d3)\n",
             "Generated by pathfinding/tools/build_single_file.py from flyx/fly_pathplan.py (commit f7b97d3),\n"
             "then SAFEGUARDED by jolie_course/drift/build_drift_files.py (robust align_to_map, gain 0.3, cap 0.6 m)\n", "safe stamp")
    compile(s, "upload_to_flyx_drift_safe.py", "exec")
    return s


def main():
    native = DRIFT.read_text(encoding="utf-8")
    skybeta_copy(native, JC / "upload_to_flyx_drift_skybeta.py",
                 "Jolie's drift-correction planner (upload_to_flyx_drift.py) on the Sky Beta contract - the drone's interface.")
    if "--no-safe" not in sys.argv:
        safe = safe_native(native)
        (JC / "upload_to_flyx_drift_safe.py").write_text(safe, encoding="utf-8", newline="\n")
        print("wrote", JC / "upload_to_flyx_drift_safe.py")
        skybeta_copy(safe, JC / "upload_to_flyx_drift_safe_skybeta.py",
                     "SAFEGUARDED drift-correction planner (upload_to_flyx_drift_safe.py) on the Sky Beta contract.")


if __name__ == "__main__":
    main()
