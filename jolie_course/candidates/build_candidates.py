"""Build candidate copies of Jolie's FlyX-proven upload_to_flyx.py with only tuned constants changed.

    python3 jolie_course/candidates/build_candidates.py            # all in sweep/results/candidates.json
    python3 jolie_course/candidates/build_candidates.py fast safe  # some of them

upload_to_flyx.py is read, never written (same pattern as build_skybeta_copy.py). Each candidate
is that file byte for byte except:
  * a comment header naming the candidate and its changed constants, and
  * the changed constants themselves, applied with the exact substitution table the offline
    sweep used (sweep/embedded.py KNOBS), so the file flies what was simulated.
The builder checks that every other line is unchanged and that the embedded sources it carries
equal the ones the sweep ran.
"""
import ast
import difflib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "sweep"))
import embedded as E   # noqa: E402

SPEC = REPO / "sweep" / "results" / "candidates.json"


def build(name, knobs, why=""):
    k = E.normalise(knobs)
    changed = {n: v for n, v in k.items() if v != E.BASE[n]}
    body = E.file_for(changed)
    header = (f"# CANDIDATE '{name}': generated by jolie_course/candidates/build_candidates.py from\n"
              f"# jolie_course/upload_to_flyx.py (FlyX-proven); only these constants differ (proven -> new):\n"
              + "".join(f"#   {n}: {E.BASE[n]} -> {v}\n" for n, v in changed.items())
              + (f"# Why: {why}\n" if why else "")
              + "# Offline-sweep result, NOT yet flown: Gazebo/FlyX shadow and team approval before it arms.\n")
    text = header + body
    compile(text, name, "exec")
    tree = ast.parse(text)
    src = next(ast.literal_eval(n.value) for n in tree.body
               if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", None) == "_SOURCES")
    assert src == E.sources_for(changed), "embedded sources differ from what the sweep ran"
    proven = E.PROVEN.read_text(encoding="utf-8").splitlines()
    diff = [d for d in difflib.unified_diff(proven, body.splitlines(), lineterm="", n=0)
            if d.startswith(("+", "-")) and not d.startswith(("+++", "---"))]
    expected = sum(len(E.KNOBS[n]) for n in changed)
    assert len(diff) == 2 * expected, f"{name}: {len(diff)} changed lines, expected {2 * expected}"
    out = HERE / f"upload_to_flyx_{name}.py"
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out.relative_to(REPO)}: {len(changed)} constants changed ({expected} lines)")
    return out


def main(argv=None):
    names = (argv if argv is not None else sys.argv[1:])
    spec = json.loads(SPEC.read_text())
    for c in spec:
        if not names or c["name"] in names:
            build(c["name"], c["knobs"], c.get("why", ""))


if __name__ == "__main__":
    main()
