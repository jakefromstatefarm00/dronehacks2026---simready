"""Build the residual copies of Jolie's FlyX-proven files (the originals are read, never written).

    python3 jolie_course/build_residual_copy.py [--policy residual/policy.json] [--drift-policy residual/policy_drift.json]

writes
    jolie_course/upload_to_flyx_residual.py          from upload_to_flyx.py          (native PX4, FlyX)
    jolie_course/upload_to_flyx_residual_skybeta.py  from upload_to_flyx_skybeta.py  (Sky Beta contract)
    jolie_course/upload_to_flyx_drift_residual.py    from residual/bases/upload_to_flyx_drift.py
        (Jolie's map-alignment build, origin/jolie-drift-correction f7b97d3), with the second residual
        trained on that base; only if --drift-policy exists

Each copy is its original byte for byte (every embedded module in _SOURCES, the map, the planner
process, the PX4 / Sky Beta I/O) plus four insertions:
  1. a docstring header saying what changed;
  2. after the embedded imports: residual/runtime.py embedded as a string and exec'd into its own
     module, the trained numpy policy (JSON), and ``_residual_choice()``;
  3. ``--no-residual`` in parse_args;
  4. in main(): ``build_planner`` and the Mission class come from ``_residual_choice``.
With --no-residual, ``_residual_choice`` returns Jolie's own ``Mission`` and ``_build_planner_embedded``
objects, so the program is exactly the original.
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
RUNTIME = REPO / "residual" / "runtime.py"
# (source file, output name in jolie_course/, which policy)
TARGETS = [(HERE / "upload_to_flyx.py", "upload_to_flyx_residual.py", "proven"),
           (HERE / "upload_to_flyx_skybeta.py", "upload_to_flyx_residual_skybeta.py", "proven"),
           (REPO / "residual" / "bases" / "upload_to_flyx_drift.py", "upload_to_flyx_drift_residual.py", "drift")]

HEADER = '''"""RESIDUAL COPY of {src}: Jolie's planner + a small trained residual on the carrot.

GENERATED by jolie_course/build_residual_copy.py from {src} (unchanged) and residual/runtime.py,
policy {policy_note}.  Do not edit; rebuild.

What the residual changes, only in NAVIGATE, every planning step (5 Hz):
    carrot length x [0.6, 1.3]   lateral carrot offset +-0.08 m   yaw-rate cap x [0.6, 1.0]
Lengthening and sideways offsets are only applied where the planner process checked the straight
line against the keep-out on its belief map. Stale odometry (> 0.3 s), a control stall in the
last 0.5 s, missing planner info or any non-finite number -> zero correction (her exact target).
Everything else -- route, turn-in-place, checkpoints, pad centring, landing, every guard -- is
her code, byte for byte.

    python3 jolie_course/{out}                 # with the residual
    python3 jolie_course/{out} --no-residual   # exactly {src}

Journal end record and the terminal summary report how often the residual acted / was zeroed.

------------------------------------------------------------------------------------------------
{orig}
"""'''

BLOCK = '''

# ============================================================================================
# Residual carrot policy (generated from residual/runtime.py + the trained numpy policy)
# ============================================================================================
_RESIDUAL_SOURCE = r\'\'\'{runtime}\'\'\'
_RESIDUAL_POLICY = json.loads(r\'\'\'{policy}\'\'\')


def _load_residual_runtime():
    import types
    mod = types.ModuleType("jolie_residual_runtime")
    mod.__file__ = "<embedded residual/runtime.py>"
    exec(compile(_RESIDUAL_SOURCE, mod.__file__, "exec"), mod.__dict__)
    return mod


_residual_rt = _load_residual_runtime()


def _residual_choice(no_residual, carrot_m):
    """(Mission class, build_planner). --no-residual: Jolie's own objects, unchanged."""
    if no_residual:
        return Mission, _build_planner_embedded
    return (_residual_rt.make_residual_mission(Mission, _RESIDUAL_POLICY),
            _residual_rt.wrap_build_planner(_build_planner_embedded, carrot_m))

'''


def _policy(policy_path):
    params = json.loads(Path(policy_path).read_text(encoding="utf-8"))
    meta = params.get("meta", {})
    policy = json.dumps({k: params[k] for k in ("format", "obs_dim", "layers")} | {"meta": meta})
    assert "'''" not in policy
    return policy, f"{Path(policy_path).name} (level {meta.get('level', '?')}, iteration {meta.get('it', '?')})"


def build(policy_path, drift_policy_path=None):
    runtime = RUNTIME.read_text(encoding="utf-8")
    assert "'''" not in runtime, "runtime.py must not contain triple single quotes"
    policies = {"proven": _policy(policy_path)}
    if drift_policy_path is not None and Path(drift_policy_path).exists():
        policies["drift"] = _policy(drift_policy_path)
    written = []
    for src, out_name, which in TARGETS:
        if which not in policies:
            continue
        policy, note = policies[which]
        src_name = src.name
        s = src.read_text(encoding="utf-8")
        original = s

        def rep(a, b, label):
            nonlocal s
            assert s.count(a) == 1, f"{label}: expected exactly one match in {src_name}"
            s = s.replace(a, b)

        i = s.index('"""')
        j = s.index('"""', i + 3) + 3
        s = s[:i] + HEADER.format(src=src_name, out=out_name, policy_note=note, orig=s[i + 3:j - 3].strip("\n")) + s[j:]
        anchor = "from pathplan.planner_process import MAX_TURN_RATE, PlannerProcess      # noqa: E402\n"
        rep(anchor, anchor + BLOCK.format(runtime=runtime, policy=policy), "embedded imports")
        rep('''    ap.add_argument("--shadow", dest="execute", action="store_false",''',
            '''    ap.add_argument("--no-residual", action="store_true",
                    help="fly Jolie's planner exactly as the original file (no residual correction)")
    ap.add_argument("--shadow", dest="execute", action="store_false",''', "--no-residual option")
        rep("    build_planner = _build_planner_embedded\n",
            "    MissionClass, build_planner = _residual_choice(a.no_residual, a.carrot)\n", "build_planner")
        rep("    mission = Mission(planner, MissionConfig(", "    mission = MissionClass(planner, MissionConfig(", "Mission")
        rep('''        print_summary(mission, planner, node, a.output / "journal.jsonl")''',
            '''        if hasattr(mission, "residual_stats"):
            print(f"residual: acted {mission.residual_stats['applied']} planning steps, zero "
                  f"{mission.residual_stats['zero']} ({mission.residual_stats['zero_reasons']})", flush=True)
            log({"kind": "residual", **mission.residual_stats})
        else:
            print("residual: OFF (--no-residual)", flush=True)
        print_summary(mission, planner, node, a.output / "journal.jsonl")''', "summary")
        compile(s, out_name, "exec")
        # the original's embedded modules must be carried over unchanged
        k0 = original.index("_SOURCES = {")
        k1 = original.index("\ndef _install_embedded():")
        assert original[k0:k1] in s, "embedded _SOURCES changed"
        (HERE / out_name).write_text(s, encoding="utf-8", newline="\n")
        written.append(out_name)
        print(f"wrote jolie_course/{out_name} ({len(s) / 1024:.0f} KB) from {src_name}")
    return written


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--policy", type=Path, default=REPO / "residual" / "policy.json")
    ap.add_argument("--drift-policy", type=Path, default=REPO / "residual" / "policy_drift.json")
    a = ap.parse_args()
    build(a.policy, a.drift_policy)
