"""Build jolie_course/upload_to_flyx_v5_skybeta.py from upload_to_flyx_v5.py (best-v5, native FlyX).

    python3 pathfinding/tools/build_single_file.py
    cp pathfinding/flyx/upload_to_flyx.py jolie_course/upload_to_flyx_v5.py
    python3 jolie_course/build_v5_skybeta.py

Uses build_skybeta_copy.py's own build() (the same PX4-I/O swap: /visual_slam/tracking/odometry +
/skybeta/state in, /skybeta/setpoint/pose out, no /fmu), pointed at the v5 file. The v5 switches
are module defaults in the embedded planner_process (V5_OPTIONS), so main() needs no change.
"""
from pathlib import Path
import importlib.util

HERE = Path(__file__).resolve().parent


class _Text:
    def __init__(self, text):
        self.text = text

    def read_text(self, encoding="utf-8"):
        return self.text


def main():
    spec = importlib.util.spec_from_file_location("build_skybeta_copy", HERE / "build_skybeta_copy.py")
    b = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(b)
    b.SRC = HERE / "upload_to_flyx_v5.py"
    b.OUT = HERE / "upload_to_flyx_v5_skybeta.py"
    # main() template: pass the turn-gate options exactly as the native fly_pathplan main() does
    # (planner_options(a) to the planner child, turns_config(a) to MissionConfig)
    tmpl = b.MAIN.read_text(encoding="utf-8")
    for a, c in ((
            '''    planner = PlannerProcess(build_planner, (a.planner, a.altitude, a.camera_offset, a.camera_pitch_down_deg,
                                             a.carrot))     # first: it forks''',
            '''    planner = PlannerProcess(build_planner, (a.planner, a.altitude, a.camera_offset, a.camera_pitch_down_deg,
                                             a.carrot, planner_options(a)))     # first: it forks'''), (
            '''        ack_timeout_s=1e9))''',
            '''        ack_timeout_s=1e9, **turns_config(a)))''')):
        assert tmpl.count(a) == 1, "skybeta_main.py.in changed; update build_v5_skybeta.py"
        tmpl = tmpl.replace(a, c)
    b.MAIN = _Text(tmpl)
    old = b.DOC
    b.DOC = b.DOC.replace(
        '"""Jolie\'s FlyX-proven planner (upload_to_flyx.py) on the Sky Beta contract - the drone\'s interface.',
        '"""BEST-V5 (Jolie\'s v4c 1d44162 + marked [v5] patches, upload_to_flyx_v5.py) on the Sky Beta contract.\n\n'
        "GENERATED by jolie_course/build_v5_skybeta.py with build_skybeta_copy.py's build(); its description\n"
        "below applies with upload_to_flyx_v5.py in place of upload_to_flyx.py.\n")
    b.DOC = b.DOC.replace("python3 jolie_course/upload_to_flyx_skybeta.py", "python3 jolie_course/upload_to_flyx_v5_skybeta.py")
    assert b.DOC != old and b.DOC.startswith('"""BEST-V5'), "build_skybeta_copy.DOC changed"
    b.build()


if __name__ == "__main__":
    main()
