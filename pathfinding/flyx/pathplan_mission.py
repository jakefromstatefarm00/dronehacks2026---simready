        from .grid_search import polyline_cost
        spec = self.spec
        cells = (np.asarray(poly)[:, ::-1] + spec.half_size) / spec.resolution - .5   # (row, col) floats
        cells = np.clip(cells, 0, cost.shape[0] - 1)
        return polyline_cost(cost, [tuple(c) for c in cells])

