"""Build the single-file FlyX node: ros2/dronehacks_pathplan/dronehacks_pathplan/pathplan_mission.py
with the planner modules and the published-course map embedded.

    python tools/build_single_file.py            # -> flyx/pathplan_mission.py

The output needs only rclpy + standard ROS message packages + numpy (scipy optional: a numpy
fallback is used without it).  It embeds the *unchanged* source of the tested pathplan
modules and installs them as an in-memory ``pathplan`` package, so it behaves exactly like
the repo version.  Re-run after changing pathplan or the node.
"""
import argparse
import base64
from hashlib import sha256
import json
from pathlib import Path
import subprocess
import sys
import zlib

import numpy as np

ROOT = Path(__file__).resolve().parents[1]          # pathfinding/
REPO = ROOT
NODE = ROOT / "ros2/dronehacks_pathplan/dronehacks_pathplan/pathplan_mission.py"
# dependency order (each module's relative imports must already be loaded)
MODULES = ["grid_search", "world", "belief", "depth_projection", "online", "ros_node"]


def build_map(altitude):
    sys.path.insert(0, str(ROOT))
    from pathplan.harness import load_published
    from pathplan.world import Envelope, GridSpec, checkpoints_from_route, occupancy
    course, route = load_published()
    spec, env = GridSpec(), Envelope()
    prior = occupancy(course, spec, altitude=altitude, half_height=env.half_height + env.tracking_margin)
    cps = [dict(name=c.name, centre=c.centre.tolist(), normal=c.normal.tolist(), half_width=c.half_width,
                points=c.points, kind=c.kind, other_route=c.other_route)
           for c in checkpoints_from_route(route, course)]
    return spec, env, prior, cps


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--altitude", type=float, default=.9)
    ap.add_argument("--output", type=Path, default=ROOT / "flyx/pathplan_mission.py")
    a = ap.parse_args()

    spec, env, prior, cps = build_map(a.altitude)
    packed = base64.b64encode(zlib.compress(np.packbits(prior).tobytes(), 9)).decode()
    sources = {m: (ROOT / "pathplan" / f"{m}.py").read_text(encoding="utf-8") for m in MODULES}
    for m, s in sources.items():
        if "'''" in s:
            raise SystemExit(f"{m}.py contains ''' and cannot be embedded as a raw string")
    try:
        commit = subprocess.run(["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"],
                                capture_output=True, text=True).stdout.strip()
    except OSError:
        commit = "unknown"

    node = NODE.read_text(encoding="utf-8")
    old = """        sys.path.insert(0, _find_pathfinding(g('pathfinding_path')))
        from pathplan.depth_projection import CameraMount
        from pathplan.ros_node import OdomFrame, build_planner
"""
    new = """        _install_pathplan()                    # embedded planner (see the end of this file)
        from pathplan.depth_projection import CameraMount
        from pathplan.ros_node import OdomFrame
        build_planner = _build_planner_embedded
"""
    if old not in node:
        raise SystemExit("pathplan_mission.py changed: update the replacement in build_single_file.py")
    node = node.replace(old, new)
    head, body = node.split('"""', 2)[1], node.split('"""', 2)[2]

    out = []
    out.append('"""THE SINGLE FILE TO GIVE FLYX: our online path planner as a skybeta competitor node.\n\n'
               'Generated by pathfinding/tools/build_single_file.py from the repo '
               f'(commit {commit}) -- do not edit by hand; edit the sources and rebuild.\n'
               'Needs only rclpy, geometry_msgs, nav_msgs, sensor_msgs, std_msgs and numpy\n'
               '(scipy is used if present).  Everything else -- the planner and the published-course\n'
               f'map at {a.altitude} m -- is embedded at the end of this file.\n\n'
               '    python3 pathplan_mission.py                       # alongside skybeta flight_interface\n'
               '    python3 pathplan_mission.py --ros-args -p shadow:=true -p depth_topic:=<topic>\n\n'
               '--- original node documentation ---\n' + head + '"""')
    out.append(body.rstrip() + "\n")
    out.append("\n\n# " + "=" * 92 + "\n# Embedded planner and course map (generated)\n# " + "=" * 92 + "\n")
    out.append(f"_MAP_ALTITUDE = {a.altitude!r}\n")
    out.append(f"_PRIOR_SHAPE = {tuple(prior.shape)!r}\n")
    out.append(f"_PRIOR_SHA256 = {sha256(prior.tobytes()).hexdigest()!r}\n")
    out.append(f"_PRIOR = {packed!r}\n")
    out.append(f"_CHECKPOINTS = {cps!r}\n")             # a Python literal (not JSON: True/False)
    out.append("_SOURCES = {\n")
    for m in MODULES:
        out.append(f"    {m!r}: r'''{sources[m]}''',\n")
    out.append("}\n")
    out.append('''

def _install_pathplan():
    """Register the embedded modules as package ``pathplan`` (idempotent)."""
    import types
    if "pathplan.online" in sys.modules:
        return
    pkg = types.ModuleType("pathplan")
    pkg.__path__ = []
    sys.modules["pathplan"] = pkg
    for name in ''' + repr(MODULES) + ''':
        mod = types.ModuleType("pathplan." + name)
        mod.__package__ = "pathplan"
        mod.__file__ = "<embedded pathplan/" + name + ".py>"
        sys.modules["pathplan." + name] = mod
        exec(compile(_SOURCES[name], mod.__file__, "exec"), mod.__dict__)
        setattr(pkg, name, mod)


def _build_planner_embedded(planner_name="theta", altitude=_MAP_ALTITUDE, chicane="window"):
    """Same as pathplan.ros_node.build_planner, from the embedded map (no course files needed)."""
    import base64, hashlib, zlib
    import numpy as np
    from pathplan.online import OnlinePlanner, PlannerConfig
    from pathplan.world import Checkpoint, Envelope, GridSpec
    if abs(altitude - _MAP_ALTITUDE) > 1e-6:
        raise ValueError(f"this file embeds the map for {_MAP_ALTITUDE} m; rebuild it for {altitude} m")
    if chicane != "window":
        raise ValueError("the embedded checkpoints are the window/Gate B route")
    n = _PRIOR_SHAPE[0] * _PRIOR_SHAPE[1]
    bits = np.frombuffer(zlib.decompress(base64.b64decode(_PRIOR)), np.uint8)
    prior = np.unpackbits(bits)[:n].astype(bool).reshape(_PRIOR_SHAPE)
    if hashlib.sha256(prior.tobytes()).hexdigest() != _PRIOR_SHA256:
        raise ValueError("embedded map is corrupt")
    cps = [Checkpoint(c["name"], np.array(c["centre"]), np.array(c["normal"]), c["half_width"], c["points"],
                      kind=c["kind"], other_route=c["other_route"]) for c in _CHECKPOINTS]
    spec, env = GridSpec(), Envelope()
    return OnlinePlanner(prior, spec, env, cps, PlannerConfig(planner=planner_name)), spec, env, prior


if __name__ == "__main__":
    main()
''')
    text = "".join(out)
    # the node's own `if __name__ == '__main__': main()` must run AFTER the embedded section
    text = text.replace("\n\nif __name__ == '__main__':\n    main()\n\n\n# " + "=" * 92,
                        "\n\n\n# " + "=" * 92, 1)
    a.output.parent.mkdir(parents=True, exist_ok=True)
    a.output.write_text(text, encoding="utf-8", newline="\n")
    compile(text, str(a.output), "exec")
    print(f"wrote {a.output} ({len(text) / 1024:.0f} KB), map {prior.shape} at {a.altitude} m, "
          f"{len(cps)} checkpoints, commit {commit}")


if __name__ == "__main__":
    main()
