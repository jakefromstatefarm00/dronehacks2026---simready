def wrap(a):
    return (a + pi) % (2 * pi) - pi


def yaw_from_q_ned(q):
    w, x, y, z = q
    return atan2(2 * (w * z + x * y), 1 - 2 * (y * y + z * z))


def dist(a, b):
    return sum((p - q) ** 2 for p, q in zip(a, b)) ** .5


def find_topic(graph, basename, type_name):
    import re
    rx = re.compile(f"/fmu/out/{re.escape(basename)}(_v[0-9]+)?")
    hits = [t for t, types_ in graph if rx.fullmatch(t) and type_name in types_]
    return hits[0] if len(hits) == 1 else None


class CourseFrame:
    """PX4 local NED <-> course frame (published map: x, y on the floor, z up), fixed at launch.

    Same construction as pathfinding/flyx/px4_link.py (used in FlyX): the vehicle sits on the launch
    mark facing LAUNCH_HEADING (course frame); its NED pose then fixes the mapping. Course z is height
    above the launch pose (the route's start is z = 0)."""

    def __init__(self, p0_ned, yaw0_ned, launch_xy=LAUNCH_XY, launch_heading=LAUNCH_HEADING):
        self.north = launch_heading + yaw0_ned          # course heading of NED north
        c, s = cos(self.north), sin(self.north)
        self.m = ((c, s, 0.0), (s, -c, 0.0), (0.0, 0.0, -1.0))   # symmetric, its own inverse
        mp = self._mul(p0_ned)
        self.origin = (launch_xy[0] - mp[0], launch_xy[1] - mp[1], 0.0 - mp[2])

    def _mul(self, v):
        return tuple(sum(self.m[i][j] * v[j] for j in range(3)) for i in range(3))

    def to_course(self, p_ned):
        mp = self._mul(p_ned)
        return tuple(a + b for a, b in zip(mp, self.origin))

    def to_ned(self, p_course):
        return self._mul(tuple(a - b for a, b in zip(p_course, self.origin)))

    def vel_to_ned(self, v_course):
        return self._mul(v_course)

    def yaw_to_course(self, yaw_ned):
        return wrap(self.north - yaw_ned)

    def yaw_to_ned(self, yaw_course):
        return wrap(self.north - yaw_course)


class Telemetry:
    def __init__(self):
        self.now = 0.0
        self.sim_now = None
        self.odom_t = self.status_t = self.landed_t = self.local_t = None
        self.odom_sim = None
        self.position = (0.0, 0.0, 0.0)
        self.velocity = (nan, nan, nan)   # NED, from vehicle_odometry (NaN if PX4 does not report it)
        self.q = (1.0, 0.0, 0.0, 0.0)
        self.pose_frame = POSE_FRAME_NED
        self.arming_state, self.nav_state = DISARMED, 0
        self.landed = False
        self.xy_valid = self.z_valid = False
        self.foreign = ""   # another node publishing PX4 setpoints (e.g. skybeta_flight_interface)


class CourseMission:
    """tick(telemetry) -> (state, setpoint (pos NED, vel NED or None, yaw NED, yawspeed) or None, command, note)."""

    def __init__(self, route=None, speed_scale=SPEED_SCALE, leash=LEASH_M, yaw_rate_max=YAW_RATE_MAX,
                 settle=SETTLE_S, max_flight=MAX_FLIGHT_S, corner_deg=CORNER_DEG):
        self.route = route or ROUTE
        self.speed_scale, self.leash, self.yaw_rate_max = speed_scale, leash, yaw_rate_max
        self.settle, self.max_flight = settle, max_flight
        self.state, self.events = "WAIT_HEALTH", []
        self.t_state = self.healthy_since = self.t_takeoff = self.offboard_lost = None
        self.frame = self.ctrl = None
        self.v_pos = self.v_vel = None          # virtual setpoint (course frame)
        self.v_yaw = self.v_yaw_rate = 0.0
        self.leashed = False
        self.done_since = None
        self.corners, self.corner_deg = set(), corner_deg
        self.last_now = self.pausing = None
        self.ref_clock = 0.0                    # the controller's clock: advances <= 0.1 s per tick
        self.land_sent = False
        self.wp_logged = 0

    # ---------------------------------------------------------------- health
    def go(self, state, now, note=""):
        self.events.append({"t": round(now, 3), "from": self.state, "to": state, "note": note})
        self.state, self.t_state = state, now

    @staticmethod
    def paused(tel):
        if tel.odom_t is not None and tel.now - tel.odom_t > ODOM_HOLD_S:
            return f"odometry paused {tel.now - tel.odom_t:.2f} s"
        return ""

    @staticmethod
    def unhealthy(tel, ground=False):
        now = tel.now
        if tel.odom_t is None:
            return "odometry never received"
        if now - tel.odom_t > (ODOM_HOLD_S if ground else OUTAGE_S):
            return f"odometry lost ({now - tel.odom_t:.2f} s)"
        if tel.foreign:
            return "another program commands PX4: " + tel.foreign
        if tel.pose_frame != POSE_FRAME_NED:
            return f"odometry frame {tel.pose_frame} is not NED"
        slow = 3.0 if ground else SLOW_LOST_S
        if tel.status_t is None or now - tel.status_t > slow:
            return "vehicle_status silent"
        if tel.local_t is None or now - tel.local_t > slow:
            return "local position silent"
        if not (tel.xy_valid and tel.z_valid):
            return f"estimator invalid (xy {tel.xy_valid}, z {tel.z_valid})"
        if not all(isfinite(v) for v in tel.position):
            return "odometry not finite"
        return ""

    def hold_here(self, tel):
        return tuple(tel.position), None, yaw_from_q_ned(tel.q), nan

    def setpoint(self):
        """PX4 target: LEAD_S ahead of the reference along its velocity, but never past the waypoint
        it is heading for, plus FF_FRAC of its velocity as feedforward. If this program stalls, PX4
        settles near that point - on the route - instead of flying on (pure velocity feedforward
        overshoots by v / MPC_XY_P, ~0.5 m; offline worst case over 1.8 s stalls: 0.13 m off route)."""
        v = self.v_vel
        speed = sum(x * x for x in v) ** .5
        p = self.v_pos
        if self.in_corner_zone():
            return (self.frame.to_ned(p), self.frame.vel_to_ned((0.0, 0.0, 0.0)),
                    self.frame.yaw_to_ned(self.v_yaw), -self.v_yaw_rate)
        if speed > 1e-6:
            tgt = self.ctrl.handoff_target if self.ctrl.done else self.ctrl.waypoints[self.ctrl.waypoint_index]["position"]
            lead = min(speed * LEAD_S, dist(self.v_pos, tgt))
            p = tuple(a + x / speed * lead for a, x in zip(self.v_pos, v))
        return (self.frame.to_ned(p), self.frame.vel_to_ned(tuple(x * FF_FRAC for x in v)),
                self.frame.yaw_to_ned(self.v_yaw), -self.v_yaw_rate)   # NED yawspeed = -course yaw rate

    def in_corner_zone(self):
        """Distance to the sharp corner the reference is heading for, if within CORNER_ZONE_M."""
        c = self.ctrl
        if c is None or c.done or self.v_pos is None or c.waypoint_index not in self.corners:
            return None
        d = dist(self.v_pos, c.waypoints[c.waypoint_index]["position"])
        return d if d < CORNER_ZONE_M else None

    # ---------------------------------------------------------------- state machine
    def tick(self, tel):
        now = tel.now
        bad = self.unhealthy(tel, ground=self.state == "WAIT_HEALTH")
        s = self.state
        if s == "WAIT_HEALTH":
            pause = self.paused(tel)
            ok = not bad and not pause and tel.landed and tel.landed_t is not None \
                and now - tel.landed_t <= 3.0 and tel.arming_state == DISARMED
            if not ok:
                self.healthy_since = None
                return s, None, None, "waiting: " + (bad or pause or "landed + disarmed")
            self.healthy_since = self.healthy_since if self.healthy_since is not None else now
            if now - self.healthy_since < self.settle:
                return s, None, None, "healthy, confirming"
            self.frame = CourseFrame(tuple(tel.position), yaw_from_q_ned(tel.q))
            p_c = self.frame.to_course(tel.position)
            self.go("STREAM", now, f"course frame from launch pose: PX4 {tuple(round(v, 3) for v in tel.position)} "
                                   f"-> course {tuple(round(v, 3) for v in p_c)}; route {self.route.get('name')}, "
                                   f"{len(self.route['waypoints'])} waypoints, speed scale {self.speed_scale}")
            return self.state, self.hold_here(tel), None, "streaming hold setpoints"
        if s == "STREAM":
            if bad:
                self.go("FAILED", now, "unhealthy before Offboard: " + bad)
                return self.state, None, None, bad
            if now - self.t_state >= 1.0:
                self.go("WAIT_OFFBOARD", now)
                return self.state, self.hold_here(tel), (CMD_DO_SET_MODE, 1.0, 6.0), "requesting Offboard"
            return s, self.hold_here(tel), None, "streaming hold setpoints"
        if s == "WAIT_OFFBOARD":
            if tel.nav_state == NAV_OFFBOARD:
                self.go("WAIT_ARM", now)
                return self.state, self.hold_here(tel), (CMD_ARM_DISARM, 1.0, 0.0), "Offboard active, arming"
            if now - self.t_state > 3.0:
                self.go("FAILED", now, "PX4 did not enter Offboard")
                return self.state, None, None, ""
            return s, self.hold_here(tel), None, "waiting for Offboard"
        if s == "WAIT_ARM":
            if tel.arming_state == ARMED:
                self.t_takeoff = now
                self.ctrl = core.CourseController(self.route, speed_scale=self.speed_scale)
                self.corners = corner_waypoints(self.route["start"], self.ctrl.waypoints, self.corner_deg)
                self.v_pos = self.frame.to_course(tel.position)
                self.v_vel = (0.0, 0.0, 0.0)
                self.v_yaw = self.frame.yaw_to_course(yaw_from_q_ned(tel.q))
                self.v_yaw_rate = 0.0
                self.last_now, self.ref_clock = now, 0.0
                self.go("FLY", now, "armed")
            elif now - self.t_state > 3.0:
                self.go("FAILED", now, "PX4 refused to arm")
                return self.state, None, None, ""
            else:
                return s, self.hold_here(tel), None, "waiting for arm"
        if self.state == "FLY":
            return self.fly(tel, now, bad)
        if self.state == "LAND":
            if tel.landed and tel.arming_state == DISARMED:
                self.go("DONE", now, "landed and disarmed")
            return self.state, None, None, "landing"
        return self.state, None, None, ""

    def fly(self, tel, now, bad):
        if tel.nav_state != NAV_OFFBOARD:
            self.offboard_lost = self.offboard_lost if self.offboard_lost is not None else now
            if now - self.offboard_lost > .5:
                self.go("TAKEN_OVER", now, f"PX4 left Offboard (nav_state {tel.nav_state}); not commanding")
                return self.state, None, None, ""
        else:
            self.offboard_lost = None
        if bad:
            return self.land(now, "unhealthy: " + bad)
        if now - self.t_takeoff > self.max_flight:
            return self.land(now, "flight time limit")
        dt = min(max(now - self.last_now, 0.0), 0.1)
        self.last_now = now
        pause = self.paused(tel)
        p_real = self.frame.to_course(tel.position)
        lag = dist(p_real, self.v_pos)
        if lag > DIVERGE_M:
            return self.land(now, f"drone {lag:.2f} m from the route reference (estimate or vehicle diverged)")
        # hysteresis: freeze above the leash, resume once the drone is back within 60 % of it
        self.leashed = lag > (0.6 * self.leash if self.leashed else self.leash)
        if pause or self.leashed:
            # freeze the reference: hold the current setpoint, zero velocity feedforward. The
            # controller is not stepped, so its clocks do not see the pause.
            why = pause or f"drone {lag:.2f} m behind the setpoint"
            if not self.pausing:
                self.pausing = now
                self.events.append({"t": round(now, 3), "hold": why, "wp": self.ctrl.waypoint_index})
            self.v_vel, self.v_yaw_rate = (0.0, 0.0, 0.0), 0.0
            self.ctrl.last_command = core.ZERO    # restart from rest, consistent with the held setpoint
            return self.state, self.setpoint(), None, "holding: " + why
        if self.pausing:
            self.events.append({"t": round(now, 3), "resume_after_s": round(now - self.pausing, 3)})
            self.pausing = None
        # friend's controller plans on the virtual setpoint (clean reference: no sensor noise, no lab
        # gaps). It runs on its own clock, stepped by the same capped dt that integrates the setpoint, so
        # a stall of this program (measured up to 1.8 s in FlyX) is a pause, not a clock fault.
        self.ref_clock += dt
        cmd = self.ctrl.update(self.v_pos, self.v_vel, self.ref_clock, offboard=True, odom_age=0.0,
                               state_age=0.0, yaw=self.v_yaw)
        if cmd.fault:
            return self.land(now, f"route controller fault: {cmd.fault}")
        while self.wp_logged < self.ctrl.waypoint_index:
            w = self.route["waypoints"][self.wp_logged] if self.wp_logged < len(self.route["waypoints"]) else {"phase": "LANDING_APPROACH"}
            self.events.append({"t": round(now, 3), "waypoint": self.wp_logged + 1, "phase": w["phase"],
                                "position": [round(v, 3) for v in p_real]})
            self.wp_logged += 1
        if cmd.done and dist(p_real, self.ctrl.handoff_target) <= LAND_TOL_M:
            return self.land(now, "course complete: over the landing pad")
        if cmd.done and dist(self.v_pos, self.ctrl.handoff_target) <= 0.02:
            self.done_since = self.done_since if self.done_since is not None else now
            if now - self.done_since > 3.0:
                return self.land(now, f"course complete: setpoint on the pad 3 s, drone "
                                      f"{dist(p_real, self.ctrl.handoff_target):.2f} m from it")
        self.v_vel = tuple(cmd.velocity)
        d = self.in_corner_zone()
        if d is not None:
            # brake gently into sharp corners: PX4 overshot 0.22-0.27 m at the first maze corner
            # (Gazebo v128/v129) when the drone arrived at ~0.6 m/s chasing the reference
            cap = max(CORNER_MIN_SPEED, (2 * CORNER_ACC * d) ** .5)
            sp = sum(x * x for x in self.v_vel) ** .5
            if sp > cap:
                self.v_vel = tuple(x * cap / sp for x in self.v_vel)
                self.ctrl.last_command = self.v_vel   # the controller continues from what was flown
        self.v_pos = tuple(p + v * dt for p, v in zip(self.v_pos, self.v_vel))
        self.v_yaw_rate = max(-self.yaw_rate_max, min(self.yaw_rate_max, cmd.yaw_rate))
        self.v_yaw = wrap(self.v_yaw + self.v_yaw_rate * dt)
        return self.state, self.setpoint(), None, f"{cmd.phase} wp {self.ctrl.waypoint_index + 1}/{len(self.ctrl.waypoints)}"

    def land(self, now, why):
        self.go("LAND", now, why)
        if not self.land_sent:
            self.land_sent = True
            return self.state, None, (CMD_NAV_LAND, 0.0, 0.0), why
        return self.state, None, None, why


def corner_waypoints(start, waypoints, limit_deg=CORNER_DEG):
    """Indices of waypoints where the route turns by more than limit_deg."""
    from math import acos, degrees
    pts = [tuple(start)] + [tuple(w["position"]) for w in waypoints]
    out = set()
    for i in range(1, len(pts) - 1):
        a = [pts[i][k] - pts[i - 1][k] for k in range(3)]
        b = [pts[i + 1][k] - pts[i][k] for k in range(3)]
        na, nb = sum(x * x for x in a) ** .5, sum(x * x for x in b) ** .5
        if na > 1e-6 and nb > 1e-6:
            c = max(-1.0, min(1.0, sum(x * y for x, y in zip(a, b)) / (na * nb)))
            if degrees(acos(c)) > limit_deg:
                out.add(i - 1)
    return out


def journal_dir():
    stamp = time.strftime("%Y%m%d-%H%M%S")
    for base in (Path(__file__).resolve().parent / "runs", Path.home() / "flyx-runs", Path("/tmp/flyx-runs")):
        try:
            d = base / f"course-{stamp}"
            d.mkdir(parents=True, exist_ok=False)
            return d
        except OSError:
            continue
    return None


