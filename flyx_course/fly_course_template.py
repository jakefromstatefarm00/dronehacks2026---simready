"""Fly the DroneHacks course with machmoon/dronehacks-sim's waypoint controller, on the Sky Beta
contract - the same interface as on the drone. No /fmu topics: the organizer's
skybeta_flight_interface owns PX4.

    bash flyx_skybeta/run.sh course              # FlyX / sim: interface + this + sim pilot
    python3 flyx_course/fly_course.py            # on the drone (or with the interface already up)
    --shadow: run everything but publish no setpoints

    subscribe  /visual_slam/tracking/odometry   cuVSLAM, ENU in odom (origin/axes = start-up pose)
    subscribe  /skybeta/state                   what PX4 is doing (offboard_active, armed, ...)
    publish    /skybeta/setpoint/pose           where to be (ENU, odom)
    publish    ~/status                         JSON {"state", "note"}: HOLD = done, pilot lands

It never arms, changes mode or lands: the safety pilot arms, the interface enters Offboard
(competitor_guide.md section 4); at the end it holds over the pad, on any fault it holds where it is,
and reports HOLD so the pilot lands. In sim flyx_skybeta/sim_pilot.py plays the pilot.

GENERATED by flyx_course/build_fly_course.py from flyx_course/fly_course_template.py and
machmoon/dronehacks-sim@@@COMMIT@@ (mission/core.py embedded verbatim, route @@ROUTE@@).
Edit the template and rebuild; do not edit this file by hand. Needs rclpy, geometry_msgs,
nav_msgs, std_msgs.

THE ALGORITHM (friend's): a 15-waypoint route through the published course - first corridor, the
maze, Gate A, tunnel, chicane, window, landing approach - with per-segment speeds, an acceleration
limit, braking into each waypoint (sqrt(2 a d)) and arrival within 8 cm before advancing. That
logic is their CourseController, unchanged. It drives a virtual reference along the route; the pose
setpoint leads it by v * LEAD_S (never past the next waypoint); a leash freezes the reference when
the vehicle lags; sharp corners are braked into; the heading faces the route 0.7 m ahead at
<= 0.25 rad/s (visual odometry dies on fast turns).

ROBUSTNESS (FlyX-tested in the earlier native version): fresh odometry + 10 s settle before the
pilot may start it; odometry pause > 0.4 s freezes the reference, > 3 s holds for the pilot;
/skybeta/state silent 10 s or no valid local position: hold; the vehicle > 0.8 m from the
reference (estimate diverged): hold; Offboard ends: stop commanding. Journal:
flyx_course/runs/course-<time>/journal.jsonl (else ~/flyx-runs, /tmp/flyx-runs).

Start ON THE LAUNCH MARK facing up the first corridor (course +y).
"""
SPEED_SCALE = 0.65   # friend's validated default for this route (Gazebo: 61.8 s, 0 contacts)
LEAD_S = 1.0        # PX4 position target leads the reference by v * LEAD_S (clamped at the next
                    # waypoint): ~1/MPC_XY_P, so PX4 tracks the reference without feedforward
FF_FRAC = 0.0       # velocity feedforward fraction (0: position targets only, like pathfinding/flyx)
LEASH_M = 0.35       # freeze the route reference when the drone lags it by more than this
HEADING_LOOKAHEAD_M = 0.7   # face the route this far ahead of the reference (pathfinding/flyx's
                            # lookahead): turns start before corners and are spread out
YAW_RATE_MAX = 0.25  # rad/s cap on the controller's yaw rate (theirs: 0.7). Visual odometry dies on
                     # fast turns: FlyX run 1 of this script lost xy ~3 s after the first maze corner at
                     # 0.5 rad/s; our failure maps had 30/40 deaths at yaw rates > 0.35 rad/s.
CORNER_DEG = 45.0    # waypoints turning more than this are "sharp corners"
CORNER_ZONE_M = 0.5  # approaching a sharp corner: brake at CORNER_ACC, no lead, no feedforward ...
CORNER_ACC = 0.3
CORNER_MIN_SPEED = 0.2   # ... but never below this: the turn happens while moving. A full stop
                         # turns the heading in place, which lost visual odometry in Gazebo v131.
DIVERGE_M = 0.8      # drone this far from the reference: the estimate or the vehicle is wrong, land
                     # (normal tracking <= 0.27 m in Gazebo; a 1.8 s program stall reaches ~0.63 m)
LAND_TOL_M = 0.15    # landing handoff reached when the drone is this close (course frame)
MAX_FLIGHT_S = 175.0 # rule 7.9: 3-minute run, margin
LAUNCH_XY = (-2.515, 0.914)   # launch mark, course frame (published map)
LAUNCH_HEADING = 1.5707963267948966   # facing up the first corridor (course +y)
ODOM_HOLD_S = 0.4    # odometry this old: hold (freeze the route) until it returns
OUTAGE_S = 3.0       # odometry missing this long in the air: land
SLOW_LOST_S = 10.0   # status / local position silent this long in the air: land
SETTLE_S = 10.0      # healthy + landed this long before Offboard/arm
GROUND_ODOM_S = 1.0  # on the ground odometry may be this old (laptop Isaac: ~6 Hz with jitter)

